"""Platform-independent lobby identity (finding 115).

Hash source paths and contents, never native executables, build paths, timestamps or Git's
commit/index. Local edits and new source files count without committing. CRLF and LF checkouts
agree. The policy is conservative: even a renderer or build-tool edit separates builds.

    python port/tools/online_identity.py [--root CHECKOUT] [--header OUTPUT]
"""
import argparse
import hashlib
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOTS = ('src', 'include', 'config', 'port')
EXTENSIONS = {'.c', '.cc', '.cpp', '.h', '.inc', '.s', '.S', '.m', '.rs', '.py',
              '.toml', '.lock', '.json', '.yaml', '.wgsl', '.js', '.java', '.gradle'}
SKIP_DIRS = {'.git', '__pycache__', 'node_modules', 'target', 'build', '.venv',
             'gen', '.gradle', '.cxx'}


def source_digest(root=ROOT):
    root = Path(root)
    paths = []
    for name in SOURCE_ROOTS:
        directory = root / name
        if not directory.is_dir():
            raise ValueError('online identity: missing source directory %s' % directory)
        for parent, dirs, files in os.walk(directory):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            paths.extend(Path(parent) / f for f in files if Path(f).suffix in EXTENSIONS)
    digest = hashlib.sha256(b'dhd-online-source-v1\0')
    for path in sorted(paths, key=lambda p: p.relative_to(root).as_posix()):
        name = path.relative_to(root).as_posix().encode('utf-8')
        content = path.read_bytes().replace(b'\r\n', b'\n')
        for item in (name, content):
            digest.update(len(item).to_bytes(8, 'little'))
            digest.update(item)
    return digest.hexdigest()[:32]


def write_header(path, root=ROOT):
    identity = source_digest(root)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('/* Generated by online_identity.py; no game data. */\n'
                    '#define DHD_ONLINE_SOURCE_ID "src1-%s"\n' % identity,
                    encoding='utf-8', newline='\n')
    return identity


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--header', type=Path)
    args = parser.parse_args()
    identity = write_header(args.header, args.root) if args.header else source_digest(args.root)
    print('src1-' + identity)


if __name__ == '__main__':
    main()
