def load_functions(asm_dir):
    """(address, size, name) of every function, from splat's .s files."""
    out = []
    pat = re.compile(r'nonmatching\s+(\S+),\s*0x([0-9A-Fa-f]+)')
    addr_pat = re.compile(r'/\*\s*[0-9A-F]+\s+([0-9A-F]{8})\s')
    for root, _, names in os.walk(asm_dir):
        for n in names:
            if not n.endswith('.s'):
                continue
            text = open(os.path.join(root, n), encoding='utf-8', errors='replace').read()
            m, a = pat.search(text), addr_pat.search(text)
            if m and a:
                out.append((int(a.group(1), 16), int(m.group(2), 16), m.group(1)))
    return sorted(set(out))


def segment(data):
    """(vaddr, bytes of the one PT_LOAD's file part)."""
    _, phs, _ = elf_info(data)
    p = next(p for p in phs if p[0] == 1)
    return p[2], data[p[1]:p[1] + p[4]]


LOADSTORE = set(range(0x20, 0x40)) | {0x1E, 0x1F}  # lb..sd, lq/sq, lwc1/swc1, lqc2/sqc2


def masked(words):
    """Address-free form of an instruction run: jal/j targets, lui immediates in the address range, the %lo half
    (addiu/ori/loads/stores off a register a lui set, or off $gp) are zeroed."""
    out, hi = [], set()
    for w in words:
        op, rs, rt = w >> 26, (w >> 21) & 31, (w >> 16) & 31
        if op in (2, 3):
            out.append(w & 0xFC000000)
            continue
        if op == 0x0F:  # lui: an address's %hi (0x0010-0x0090: the ELF and its .bss), else a constant (floats)
            if 0x0010 <= (w & 0xFFFF) <= 0x0090:
                out.append(w & 0xFFFF0000)
                hi.add(rt)
            else:
                out.append(w)
                hi.discard(rt)
            continue
        if (op in (0x09, 0x0D) or op in LOADSTORE) and (rs in hi or rs == 28):
            out.append(w & 0xFFFF0000)
        else:
            out.append(w)
        # the destination register stops holding a %hi
        if op == 0:
            hi.discard((w >> 11) & 31)
        elif op in (0x09, 0x0D, 0x0A, 0x0B, 0x0C, 0x0E, 0x18, 0x19) or 0x20 <= op <= 0x27 or op == 0x37 or op == 0x1E:
            if op not in (0x09, 0x0D) or rs not in hi or rt != rs:
                hi.discard(rt)
    return tuple(out)


def region(addr):
    return next((n for a, b, n in REGIONS if a <= addr < b), 'other')


def cmd_code(elfs, asm_dir):
    funcs = [f for f in load_functions(asm_dir) if f[0] < 0x263BC0]
    base_a, seg_a = segment(elfs[0][1])
    base_b, seg_b = segment(elfs[1][1])
    _, _, shs_b = elf_info(elfs[1][1])
    text_b = next(((a, s) for n, a, o, s in shs_b if n == '.text'), None)
    text_end_b = text_b[0] + text_b[1] if text_b else base_b + len(seg_b)
    words_a = struct.unpack_from(f'<{len(seg_a) // 4}I', seg_a)
    nb = (text_end_b - base_b) // 4
    words_b = struct.unpack_from(f'<{nb}I', seg_b)
    mb = masked(words_b)  # one pass: register state carries across function edges, close enough
    raw_b = {}
    index = collections.defaultdict(list)
    K = 4
    for i in range(nb - K):
        index[mb[i:i + K]].append(i)
    print(f'A: {len(funcs)} functions; B .text 0x{base_b:06X}-0x{text_end_b:06X} ({nb * 4:,} bytes)')

    result = []  # (addr, size, name, kind, b_index or None)
    prev_shift = None
    for addr, size, name in funcs:
        n = size // 4
        ia = (addr - base_a) // 4
        wa = words_a[ia:ia + n]
        ma = masked(wa)
        cands = index.get(ma[:K], []) if n >= K else []
        hits = [i for i in cands if mb[i:i + n] == ma] if n >= K else []
        if n < K:  # tiny: only where the neighbours' shift puts it
            if prev_shift is not None:
                i = ia + prev_shift
                if 0 <= i < nb and mb[i:i + n] == ma:
                    hits = [i]
        pick = None
        if hits:
            if prev_shift is not None and ia + prev_shift in hits:
                pick = ia + prev_shift
            else:
                pick = min(hits, key=lambda i: abs(i - ia - (prev_shift or 0)))
        if pick is not None:
            kind = 'identical' if tuple(words_b[pick:pick + n]) == tuple(wa) else 'masked'
            prev_shift = pick - ia
            result.append([addr, size, name, kind, pick])
        else:
            result.append([addr, size, name, None, None])

    # unmatched: look between the matched neighbours (order kept), take the best similar run
    ends, starts, last = [], [0] * len(result), 0
    for r in result:
        if r[3]:
            last = r[4] + r[1] // 4
        ends.append(last)
    nxt = nb
    for k in range(len(result) - 1, -1, -1):
        starts[k] = nxt
        if result[k][3]:
            nxt = result[k][4]
    for k, r in enumerate(result):
        if r[3]:
            continue
        lo, hi = ends[k], starts[k]
        n = r[1] // 4
        ma = masked(words_a[(r[0] - base_a) // 4:(r[0] - base_a) // 4 + n])
        if hi - lo <= 0 or hi - lo > 40000:
            r[3] = 'not found'
            r.extend([0.0, 'no matched neighbours to search between'])
            continue
        sm = difflib.SequenceMatcher(None, ma, mb[lo:hi], autojunk=False)
        blocks = sm.get_matching_blocks()
        same = sum(b.size for b in blocks)
        r[3] = 'changed' if same >= 0.5 * n else 'not found'
        r[4] = None
        sim = same / n if n else 0
        how = ''
        if r[3] == 'changed':
            first = max(blocks, key=lambda b: b.size)
            start = lo + first.b - first.a
            r[4] = max(lo, start)
            wb = mb[start:start + n]
            # same length and the same opcodes/registers: only immediates differ
            if len(wb) == n and all(x >> 16 == y >> 16 or (x >> 26 == 0 and y >> 26 == 0 and x == y) for x, y in zip(ma, wb)):
                diff = [(x, y) for x, y in zip(ma, wb) if x != y]
                ops = collections.Counter('load/store' if x >> 26 in LOADSTORE else 'addiu/ori' if x >> 26 in (9, 13)
                                          else 'branch' if x >> 26 in (1, 4, 5, 6, 7, 0x14, 0x15, 0x16, 0x17) else 'other'
                                          for x, _ in diff)
                how = 'immediates only: ' + ', '.join(f'{k} {v}' for k, v in ops.most_common())
                r[3] = 'changed imm' if diff else 'masked'
            else:
                how = f'{n - same} of {n} instructions not found in order'
        r.extend([sim, how])

    kinds = ('identical', 'masked', 'changed imm', 'changed', 'not found')
    print(f'\nby region: functions (bytes) {" / ".join(kinds)}')
    for _, _, reg in REGIONS + [(0, 0, 'all')]:
        rows = [r for r in result if reg == 'all' or region(r[0]) == reg]
        c = collections.Counter(r[3] for r in rows)
        b = collections.Counter()
        for r in rows:
            b[r[3]] += r[1]
        cells = ' / '.join(f'{c[k]} ({b[k]:,})' for k in kinds)
        print(f'  {reg:7} {len(rows):5}: {cells}')
    imm = collections.Counter()
    for r in result:
        if r[3] == 'changed imm':
            for part in r[6].split(': ', 1)[1].split(', '):
                k, v = part.rsplit(' ', 1)
                imm[k] += int(v)
    print(f'  immediates that differ in "changed imm" functions, by instruction: {dict(imm)}')

    # shift runs: consecutive matched functions with the same B-A shift
    print('\nshift runs (A range -> shift in bytes, functions):')
    runs = []
    for r in result:
        if r[3] in ('identical', 'masked'):
            s = (r[4] - (r[0] - base_a) // 4) * 4 + (base_b - base_a)
            if runs and runs[-1][2] == s:
                runs[-1][1] = r[0] + r[1]
                runs[-1][3] += 1
            else:
                runs.append([r[0], r[0] + r[1], s, 1])
    big = [x for x in runs if x[3] >= 20]
    for a0, a1, s, n in big:
        print(f'  0x{a0:06X}-0x{a1:06X} {s:+#x} {n}')
    print(f'  ({len(runs)} runs, {len(big)} of 20+ functions shown; {sum(x[3] for x in big)} functions in them)')

    covered = set()
    for r in result:
        if r[3] in ('identical', 'masked', 'changed imm', 'changed') and r[4] is not None:
            covered.update(range(r[4], r[4] + r[1] // 4))
    extra = nb - len(covered)
    print(f'\nB .text not covered by any A function: {extra * 4:,} bytes ({extra * 100 / nb:.1f}%)')
    gaps, start = [], None
    for i in range(nb + 1):
        if i < nb and i not in covered and words_b[i] != 0:
            start = i if start is None else start
        elif start is not None:
            gaps.append((start, i))
            start = None
    big_gaps = sorted(gaps, key=lambda g: g[0] - g[1])[:15]
    print(f'  {len(gaps)} uncovered runs; the largest (B address, bytes):')
    for g0, g1 in sorted(big_gaps):
        print(f'    0x{base_b + 4 * g0:06X} {4 * (g1 - g0):,}')
    for kind in ('changed imm', 'changed', 'not found'):
        rows = [r for r in result if r[3] == kind]
        print(f'\n{kind} ({len(rows)}): name, A address, size, similarity, region, what differs')
        for r in rows:
            print(f'  {r[2]:28} 0x{r[0]:06X} {r[1]:6} {r[5]:.2f} {region(r[0]):6} {r[6]}')
    return result


def cmd_data(elfs):
    """Each data section of A against B's: words in A's order also in B's (pointer-like words,
    0x100000-0x8C0000, compared as one token), and for .rodata/.data the strings."""
    secs = ('.vutext', '.data', '.rodata', '.gcc_except_table', '.sdata')
    info = [{s[0]: s for s in elf_info(d)[2]} for _, d in elfs]
    ptr = lambda w: 0x100000 <= w < 0x8C0000
    print('section: A bytes -> B bytes; A words found in order in B (pointer words as tokens); '
          'A pointer words; runs of 16+ words')
    for name in secs:
        (_, aa, ao, asz), (_, ba_, bo, bsz) = info[0][name], info[1][name]
        wa = struct.unpack_from(f'<{asz // 4}I', elfs[0][1], ao)
        wb = struct.unpack_from(f'<{bsz // 4}I', elfs[1][1], bo)
        ma = [-1 if ptr(w) else w for w in wa]
        mb = [-1 if ptr(w) else w for w in wb]
        sm = difflib.SequenceMatcher(None, ma, mb, autojunk=False)
        blocks = sm.get_matching_blocks()
        same = sum(b.size for b in blocks)
        runs = [b for b in blocks if b.size >= 16]
        print(f'  {name:18} {asz:>8,} -> {bsz:>8,}  {same * 100 / len(wa):5.1f}% ({same:,} of {len(wa):,})  '
              f'{sum(map(ptr, wa)):,}  {len(runs)} runs, {sum(b.size for b in runs) * 100 / len(wa):.1f}% of A')
        if name == '.vutext':
            diff = [i for i in range(min(len(wa), len(wb))) if wa[i] != wb[i]]
            print(f'    same address: {len(diff)} words differ, {sum(ptr(wa[i]) for i in diff)} of them pointer-like')
    for name in ('.data', '.rodata', '.sdata'):
        strs = []
        for (_, d), inf in zip(elfs, info):
            _, _, o, sz = inf[name]
            strs.append(collections.Counter(re.findall(rb'[\x20-\x7e]{4,}', d[o:o + sz])))
        a, b = strs
        print(f'  {name} strings of 4+ printable bytes: A {sum(a.values()):,} ({len(a):,} distinct), B {sum(b.values()):,} '
              f'({len(b):,} distinct); A strings not in B {len(set(a) - set(b)):,}, B strings not in A {len(set(b) - set(a)):,}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('a')
    ap.add_argument('b')
    ap.add_argument('what', nargs='*', default=['files', 'elf'])
    ap.add_argument('--asm', default='asm/nonmatchings')
    o = ap.parse_args()
    us, eu = Iso(o.a), Iso(o.b)
    elfs = [(boot_name(i)[0], i.read(boot_name(i)[0])) for i in (us, eu)]
    for w in o.what:
        print(f'==== {w}')
        {'files': lambda: cmd_files(us, eu), 'elf': lambda: cmd_elf(us, eu, elfs),
         'code': lambda: cmd_code(elfs, o.asm), 'data': lambda: cmd_data(elfs)}[w]()


if __name__ == '__main__':
    main()
