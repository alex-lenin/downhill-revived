"""Compares two releases of Downhill Domination from the player's own disc images (finding 100)
and prints statistics only: no game bytes. Read in place, nothing extracted.

  files: SYSTEM.CNF's boot and video lines, the file lists (same, changed, only on one side),
         per folder.
  elf:   both boot ELFs' program and section headers.
  code:  how the reference ELF's functions (the decomp's function list: the .s files of
         asm/nonmatchings, generated by splat from your own SCUS_971.77) appear in the other ELF:
         byte-identical, identical once addresses are masked (jal targets, lui/%lo pairs,
         $gp offsets), changed (found between matched neighbours, similar), or not found;
         with the address shift of each matched run.
  data:  how the reference data image (0x263BC0-0x29DCF0, what game_data.c loads) lines up
         with the other ELF's data (aligned 16-byte blocks, word-masked).

usage: python port/tools/release_compare.py USA.iso OTHER.iso [files|elf|code|data ...]
                                           [--asm PATH/asm/nonmatchings]"""
import argparse
import bisect
import collections
import difflib
import hashlib
import os
import re
import struct
import sys
import zlib

SECTOR = 2048
REGIONS = [  # tools/queue.py
    (0x10A000, 0x10A208, 'crt0'),
    (0x10A208, 0x1FC000, 'game'),
    (0x1FC000, 0x201000, 'libgcc'),
    (0x201000, 0x243000, 'engine'),
    (0x243000, 0x263BC0, 'sdk'),
]


class Iso:
    """A plain ISO 9660 walk (primary volume descriptor, no Joliet): {path: (lsn, size)}."""

    def __init__(self, path):
        self.f = open(path, 'rb')
        pvd = self.sector(16)
        if pvd[0] != 1 or pvd[1:6] != b'CD001':
            sys.exit(f'{path}: no ISO 9660 volume')
        self.files = {}
        self.walk(*struct.unpack_from('<I', pvd, 156 + 2), struct.unpack_from('<I', pvd, 156 + 10)[0], '')

    def sector(self, lsn, n=1):
        self.f.seek(lsn * SECTOR)
        return self.f.read(n * SECTOR)

    def walk(self, lsn, size, prefix):
        data = self.sector(lsn, (size + SECTOR - 1) // SECTOR)
        for base in range(0, size, SECTOR):
            i = base
            while i < base + SECTOR and data[i]:
                n = data[i]
                at, length, flags, nl = struct.unpack_from('<I', data, i + 2)[0], struct.unpack_from('<I', data, i + 10)[0], data[i + 25], data[i + 32]
                name = data[i + 33:i + 33 + nl]
                if name not in (b'\0', b'\1'):
                    name = name.decode('ascii').split(';')[0]
                    if flags & 2:
                        self.walk(at, length, prefix + name + '/')
                    else:
                        self.files[prefix + name] = (at, length)
                i += n

    def read(self, name):
        at, size = self.files[name]
        return self.sector(at, (size + SECTOR - 1) // SECTOR)[:size]

    def sha1(self, name):
        at, size = self.files[name]
        h = hashlib.sha1()
        self.f.seek(at * SECTOR)
        left = size
        while left:
            chunk = self.f.read(min(left, 1 << 22))
            h.update(chunk)
            left -= len(chunk)
        return h.hexdigest()


def boot_name(iso):
    cnf = iso.read('SYSTEM.CNF').decode('ascii', 'replace')
    m = re.search(r'BOOT2\s*=\s*cdrom0:\\([^;\r\n]+)', cnf)
    return m.group(1), cnf


def payload(data):
    """The content of a file in the game's IE container (a zip local file header with 'IE' for
    'PK': method at +8, the dates at +10, CRC at +14, sizes at +18/+22, name and extra lengths at
    +26/+28; stored or raw deflate, possibly nested), else the file itself."""
    for _ in range(64):
        if data[:4] != b'IE\x03\x04':
            return data
        method, csize, nl, el = (struct.unpack_from('<H', data, 8)[0], struct.unpack_from('<I', data, 18)[0],
                                 *struct.unpack_from('<HH', data, 26))
        body = data[30 + nl + el:30 + nl + el + csize]
        data = body if method == 0 else zlib.decompressobj(-15).decompress(body)
    return data


def mpeg_video(iso, name):
    """The first MPEG video sequence header of a .PSS: width, height, frame rate."""
    at, _ = iso.files[name]
    iso.f.seek(at * SECTOR)
    head = iso.f.read(1 << 20)
    i = head.find(b'\0\0\1\xb3')
    if i < 0:
        return None
    w = head[i + 4] << 4 | head[i + 5] >> 4
    h = (head[i + 5] & 15) << 8 | head[i + 6]
    rate = {1: '23.976', 2: '24', 3: '25', 4: '29.97', 5: '30', 6: '50', 7: '59.94', 8: '60'}.get(head[i + 7] & 15, '?')
    return f'{w}x{h} {rate}'


def cmd_files(us, eu):
    for tag, iso in (('A', us), ('B', eu)):
        boot, cnf = boot_name(iso)
        lines = [l.strip() for l in cnf.splitlines() if l.strip()]
        total = sum(s for _, s in iso.files.values())
        print(f'{tag}: {len(iso.files)} files, {total:,} bytes; SYSTEM.CNF: {" | ".join(lines)}')
    a, b = set(us.files), set(eu.files)
    folder = lambda p: p.rsplit('/', 1)[0] if '/' in p else '(root)'
    stats = collections.defaultdict(lambda: collections.Counter())
    changed, only_a, only_b = [], sorted(a - b), sorted(b - a)
    for p in sorted(a & b):
        sa, sb = us.files[p][1], eu.files[p][1]
        same = sa == sb and us.sha1(p) == eu.sha1(p)
        kind = 'same'
        if not same:
            kind = 'changed'
            if sa < (64 << 20) and sb < (64 << 20) and not p.endswith('.PSS'):
                pa, pb = payload(us.read(p)), payload(eu.read(p))
                if pa == pb:
                    kind = 'wrapper'  # only the container's dates/CRC fields differ
                elif len(pa) == len(pb):
                    kind = 'same size'
                    changed.append((p, sa, sb, sum(x != y for x, y in zip(pa, pb)), len(pa)))
                else:
                    changed.append((p, sa, sb, None, (len(pa), len(pb))))
            else:
                changed.append((p, sa, sb, None, None))
        stats[folder(p)][kind] += 1
    for p in only_a:
        stats[folder(p)]['only A'] += 1
    for p in only_b:
        stats[folder(p)]['only B'] += 1
    keys = ('same', 'wrapper', 'same size', 'changed', 'only A', 'only B')
    print(f'\nper folder ({" / ".join(keys)}; wrapper: equal content in a re-made container;'
          ' same size: content of equal size with bytes changed):')
    for d in sorted(stats):
        print(f'  {d:12} ' + ' '.join(f'{stats[d][k]:5}' for k in keys))
    print('  total        ' + ' '.join(f'{sum(s[k] for s in stats.values()):5}' for k in keys))
    print(f'\ncontent changed ({len(changed)}): name, file size A -> B, content bytes changed / content size(s)')
    for p, sa, sb, nd, cs in changed:
        extra = f'{nd:,} of {cs:,}' if nd is not None else (f'content {cs[0]:,} -> {cs[1]:,}' if cs else '')
        if p.endswith('.PSS'):
            extra = f'{mpeg_video(us, p)} -> {mpeg_video(eu, p)}'
        print(f'  {p:24} {sa:>11,} -> {sb:>11,}  {extra}')
    for tag, lst, iso in (('A', only_a, us), ('B', only_b, eu)):
        print(f'\nonly on {tag} ({len(lst)}, {sum(iso.files[p][1] for p in lst):,} bytes):')
        for p in lst:
            extra = mpeg_video(iso, p) if p.endswith('.PSS') else ''
            print(f'  {p:24} {iso.files[p][1]:>11,}  {extra}')
    same_pss = [p for p in sorted(a & b) if p.endswith('.PSS') and stats and us.files[p][1] == eu.files[p][1]]
    for p in same_pss:
        print(f'  same movie {p}: {mpeg_video(us, p)}')


def elf_info(data):
    e_phoff, e_shoff = struct.unpack_from('<II', data, 0x1C)
    e_phnum, e_shentsize, e_shnum, e_shstrndx = struct.unpack_from('<HHHH', data, 0x2C)
    entry = struct.unpack_from('<I', data, 0x18)[0]
    phs = [struct.unpack_from('<8I', data, e_phoff + 32 * i) for i in range(e_phnum)]
    shs = []
    if e_shoff and e_shnum:
        raw = [struct.unpack_from('<10I', data, e_shoff + e_shentsize * i) for i in range(e_shnum)]
        strtab = raw[e_shstrndx]
        for s in raw:
            name = data[strtab[4] + s[0]:].split(b'\0', 1)[0].decode()
            shs.append((name, s[3], s[4], s[5]))  # name, addr, offset, size
    return entry, phs, shs


def cmd_elf(us, eu, elfs):
    for tag, (name, data) in zip('AB', elfs):
        entry, phs, shs = elf_info(data)
        print(f'{tag}: {name}, {len(data):,} bytes, SHA-1 {hashlib.sha1(data).hexdigest()[:8]}..., entry 0x{entry:06X}')
        for p in phs:
            print(f'  PT type {p[0]} offset 0x{p[1]:X} vaddr 0x{p[2]:06X} filesz 0x{p[4]:X} memsz 0x{p[5]:X}')
        for n, addr, off, size in shs:
            if n:
                print(f'  {n:20} 0x{addr:06X}-0x{addr + size:06X} size 0x{size:X} ({size:,})')


