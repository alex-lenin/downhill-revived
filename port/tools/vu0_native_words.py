"""The word arrays of the native VU0 routines (vu0_native.h), for a build without the VU1 blocks.

    python port/tools/vu0_native_words.py build/wasm/vu1aot/vu1_aot.inc build/wasm/vu0_native_words.inc

build_wasm.py runs it on the vu1_aot.inc it generates (port/tools/vu1_aot.py).

The wasm module runs VU0 but not VU1 (the host does), so it compiles vu0_interp.c with
-DPS2_VU0_NATIVE instead of the whole vu1_aot.inc (-DPS2_VU_AOT, 60,000 lines of VU1 blocks).
The native VU0 routines only need their five word arrays, which ps2_vu_aot_load fills from
the game's .vutext exactly as vu1_aot.inc's aot_words_load does. This takes the arrays' sizes
and their fill entries (PS2 source address, count) from the generated vu1_aot.inc, so the
generator stays the one source. No microcode word is copied: the arrays start zeroed.
"""
import re
import sys
from pathlib import Path

NAMES = ('vu0_cull_words', 'vu0_basis_words', 'vu0_bounds_words', 'vu0_length_words', 'vu0_direction_words')


def derive(inc, out):
    text = Path(inc).read_text()
    sizes = {}
    for name in NAMES:
        m = re.search(r'^AOT_WORDS\(%s, (\d+),' % name, text, re.M)
        if not m:
            raise SystemExit('%s: no AOT_WORDS(%s, ...)' % (inc, name))
        sizes[name] = int(m.group(1))
    fills = re.findall(r'^\s*\{(vu0_\w+_words), (\d+), (0x[0-9A-Fa-f]+), (\d+)\},$', text, re.M)
    covered = {n: 0 for n in NAMES}
    for name, at, _, count in fills:
        if name not in covered:
            raise SystemExit('%s: unknown fill entry %s' % (inc, name))
        covered[name] += int(count)
    for name in NAMES:
        if covered[name] != sizes[name]:
            raise SystemExit('%s: %s has %d words, its fill entries %d' % (inc, name, sizes[name], covered[name]))
    lines = ['/* Generated by port/tools/vu0_native_words.py from vu1_aot.inc. Do not commit. */']
    lines += ['static uint32_t %s[%d];' % (n, sizes[n]) for n in NAMES]
    lines += ['static const struct { uint32_t *words; unsigned at, source, count; } vu0_native_words_fill[] = {']
    lines += ['    {%s, %s, %s, %s},' % f for f in fills]
    lines += ['};', 'static void vu0_native_words_load(const uint8_t *vutext) {',
              '    for (unsigned i = 0; i < sizeof vu0_native_words_fill / sizeof *vu0_native_words_fill; i++)',
              '        memcpy(vu0_native_words_fill[i].words + vu0_native_words_fill[i].at,',
              '               vutext + (vu0_native_words_fill[i].source - 0x263BC0), vu0_native_words_fill[i].count * 4);',
              '}', '']
    Path(out).write_text('\n'.join(lines))
    return len(fills)


if __name__ == '__main__':
    print('%d fill entries' % derive(sys.argv[1], sys.argv[2]))
